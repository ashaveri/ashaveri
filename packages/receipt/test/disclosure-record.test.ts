import { describe, expect, it } from 'vitest';
import { sha256 } from '@noble/hashes/sha2.js';
import {
  DISCLOSURE_DUTY_CITATIONS,
  DISCLOSURE_DUTY_POINTERS,
  DISCLOSURE_RECORD_LIMITS,
  DISCLOSURE_RECORD_V1_MEMBERS,
  DISCLOSURE_TEXT_MAX_UNITS,
  DISCLOSURE_TRANSFORMATION_OUTCOMES,
  MARKING_SCHEMES,
  ReceiptError,
  disclosureRecordBytes,
  encodeDisclosureRecord,
  parseDisclosureRecord,
  toHex,
  type DisclosureRecord,
} from '../src/index.js';

/**
 * The disclosure record's strict reader, driven over the bytes of a file rather than over objects:
 * what a reader meets is text a deployment wrote, and the refusals below are the ones that text earns.
 * Every refusal case names the code the reader answers with, because a caller branches on the code and
 * a reader that refused everything under one string would leave the duty registry's widening
 * indistinguishable from a writer's typo.
 */

const REGION_DIGEST = toHex(sha256(new TextEncoder().encode('"ashaveri": { "marking": { "sch": "ashaveri/provenance-v1", "gen": "ai", "at": 1772000000 } }')));

const RECORD: DisclosureRecord = {
  v: 1,
  obligor: 'the deployer serving the completion',
  duty: 'ai-act-50-4',
  scheme: 'provenance-v1',
  served: { kind: 'text', text: 'This response was generated by an AI system.' },
  transformations: [
    { name: 'byte-copy', outcome: 'detectable' },
    { name: 'text-render', outcome: 'not-detectable' },
    { name: 'pixel-render', outcome: 'untested' },
  ],
  limits: DISCLOSURE_RECORD_LIMITS,
};

const encoded = (value: string): Uint8Array => new TextEncoder().encode(value);

/**
 * One edit to the writer's own bytes, every other byte left as the writer wrote it. The writer's format
 * is `JSON.stringify` at two spaces with a trailing newline, so parsing that text, moving one position
 * and writing it back in the same format reproduces the writer's bytes everywhere except the edit.
 */
function edited(mutate: (document: Record<string, unknown>) => void): Uint8Array {
  const document = JSON.parse(new TextDecoder().decode(encodeDisclosureRecord(RECORD))) as Record<string, unknown>;
  mutate(document);
  return encoded(`${JSON.stringify(document, null, 2)}\n`);
}

function refusalOf(bytes: Uint8Array): ReceiptError {
  try {
    parseDisclosureRecord(bytes);
  } catch (err) {
    if (err instanceof ReceiptError) return err;
    throw err;
  }
  throw new Error('the reader accepted a document this case states it refuses');
}

describe('the disclosure record round trip', () => {
  it('reads back what the writer wrote, member for member', () => {
    expect(parseDisclosureRecord(encodeDisclosureRecord(RECORD))).toEqual(RECORD);
  });

  it('writes one byte string for one record state, newline terminated', () => {
    const once = encodeDisclosureRecord(RECORD);
    expect(encodeDisclosureRecord(RECORD)).toEqual(once);
    expect(new TextDecoder().decode(once).endsWith('\n')).toBe(true);
  });

  it('emits the members in the order the layout declares', () => {
    const document = JSON.parse(new TextDecoder().decode(encodeDisclosureRecord(RECORD))) as Record<string, unknown>;
    expect(Object.keys(document)).toEqual([...DISCLOSURE_RECORD_V1_MEMBERS]);
  });

  it('refuses at the writer what the reader refuses, before the bytes are filed', () => {
    expect(() => disclosureRecordBytes({ ...RECORD, limits: 'limits of this record\'s own wording' })).toThrow(ReceiptError);
    expect(() => disclosureRecordBytes({ ...RECORD, duty: 'ai-act-50-2' as DisclosureRecord['duty'] })).toThrow(ReceiptError);
  });

  it('accepts every duty pointer the registry enumerates, and a citation for each', () => {
    for (const duty of DISCLOSURE_DUTY_POINTERS) {
      const record: DisclosureRecord = { ...RECORD, duty };
      expect(parseDisclosureRecord(encodeDisclosureRecord(record)).duty).toBe(duty);
      expect(DISCLOSURE_DUTY_CITATIONS[duty].length).toBeGreaterThan(0);
    }
    expect(Object.keys(DISCLOSURE_DUTY_CITATIONS).sort()).toEqual([...DISCLOSURE_DUTY_POINTERS].sort());
  });

  it('accepts every marking scheme the registry carries, and the region arm beside provenance-v1', () => {
    for (const scheme of MARKING_SCHEMES) {
      const served = scheme === 'none' ? RECORD.served : { kind: 'region', sha256: REGION_DIGEST } as const;
      const record: DisclosureRecord = { ...RECORD, scheme, served };
      expect(parseDisclosureRecord(encodeDisclosureRecord(record)).scheme).toBe(scheme);
    }
  });

  it('accepts every outcome the layout enumerates, unsupported ones recorded rather than omitted', () => {
    for (const outcome of DISCLOSURE_TRANSFORMATION_OUTCOMES) {
      const record: DisclosureRecord = { ...RECORD, transformations: [{ name: 'one-transformation', outcome }] };
      expect(parseDisclosureRecord(encodeDisclosureRecord(record)).transformations[0]?.outcome).toBe(outcome);
    }
  });
});

describe('the reader refuses a malformed record', () => {
  it('refuses a member the layout requires and the document leaves out', () => {
    for (const member of DISCLOSURE_RECORD_V1_MEMBERS) {
      const err = refusalOf(edited((document) => delete document[member]));
      expect(err.code, `missing ${member}`).toBe('DISCLOSURE_RECORD_BAD_DOCUMENT');
    }
  });

  it('refuses a member the layout does not define', () => {
    const err = refusalOf(edited((document) => { document['not_a_member'] = 1; }));
    expect(err.code).toBe('DISCLOSURE_RECORD_BAD_DOCUMENT');
    expect(err.message).toContain('not_a_member');
  });

  it('refuses a text member of the wrong type, empty, padded, or forging its printed line', () => {
    for (const value of [5, '', ' padded', 'padded ', 'line\u202eforging']) {
      const err = refusalOf(edited((document) => { document['obligor'] = value; }));
      expect(err.code, `obligor ${JSON.stringify(value)}`).toBe('DISCLOSURE_RECORD_BAD_DOCUMENT');
    }
  });

  it('refuses a text member wider than the ceiling the layout states', () => {
    const err = refusalOf(edited((document) => { document['obligor'] = 'a'.repeat(DISCLOSURE_TEXT_MAX_UNITS + 1); }));
    expect(err.code).toBe('DISCLOSURE_RECORD_BAD_DOCUMENT');
  });

  it('refuses a version that is not an integer, and one no layout reads', () => {
    expect(refusalOf(edited((document) => { document['v'] = '1'; })).code).toBe('DISCLOSURE_RECORD_BAD_DOCUMENT');
    expect(refusalOf(edited((document) => { document['v'] = 2; })).code).toBe('DISCLOSURE_RECORD_UNSUPPORTED_VERSION');
  });

  it('refuses a member named twice, while the bytes still carry both', () => {
    const bytes = encoded('{"v": 1, "v": 1}\n');
    expect(refusalOf(bytes).code).toBe('DISCLOSURE_RECORD_BAD_DOCUMENT');
  });

  it('refuses a float wearing an integer, while the characters are still distinguishable', () => {
    const bytes = encoded(new TextDecoder().decode(encodeDisclosureRecord(RECORD)).replace('"v": 1', '"v": 1.0'));
    expect(refusalOf(bytes).code).toBe('DISCLOSURE_RECORD_BAD_DOCUMENT');
  });

  it('refuses bytes that are not one JSON document', () => {
    expect(refusalOf(encoded('')).code).toBe('DISCLOSURE_RECORD_BAD_DOCUMENT');
    expect(refusalOf(encoded('{}{}\n')).code).toBe('DISCLOSURE_RECORD_BAD_DOCUMENT');
    expect(refusalOf(encoded('[]\n')).code).toBe('DISCLOSURE_RECORD_BAD_DOCUMENT');
  });

  it('refuses a served member of no arm the layout defines', () => {
    for (const served of [null, 'text', { kind: 'audio', text: 'x' }, { kind: 'text' }, { kind: 'region' }]) {
      const err = refusalOf(edited((document) => { document['served'] = served; }));
      expect(err.code, `served ${JSON.stringify(served)}`).toBe('DISCLOSURE_RECORD_BAD_DOCUMENT');
    }
  });

  it('refuses a region digest of the wrong width or spelling', () => {
    for (const sha256 of ['', 'AB'.repeat(32), 'ab'.repeat(31), 'g'.repeat(64)]) {
      const err = refusalOf(edited((document) => { document['served'] = { kind: 'region', sha256 }; }));
      expect(err.code, `digest ${sha256.slice(0, 8)}`).toBe('DISCLOSURE_RECORD_BAD_DOCUMENT');
    }
  });

  it('refuses a region served beside a scheme that declares no region', () => {
    const err = refusalOf(edited((document) => {
      document['scheme'] = 'none';
      document['served'] = { kind: 'region', sha256: REGION_DIGEST };
    }));
    expect(err.code).toBe('DISCLOSURE_RECORD_BAD_DOCUMENT');
    expect(err.message).toContain('contradicting itself');
  });

  it('refuses a transformation list that is empty, mis-typed, or names one transformation twice', () => {
    expect(refusalOf(edited((document) => { document['transformations'] = []; })).code).toBe('DISCLOSURE_RECORD_BAD_DOCUMENT');
    expect(refusalOf(edited((document) => { document['transformations'] = 'byte-copy'; })).code).toBe('DISCLOSURE_RECORD_BAD_DOCUMENT');
    const twice = refusalOf(edited((document) => {
      document['transformations'] = [
        { name: 'byte-copy', outcome: 'detectable' },
        { name: 'byte-copy', outcome: 'not-detectable' },
      ];
    }));
    expect(twice.code).toBe('DISCLOSURE_RECORD_BAD_DOCUMENT');
    expect(twice.message).toContain('twice');
  });

  it('refuses an outcome outside the three the layout enumerates', () => {
    const err = refusalOf(edited((document) => {
      document['transformations'] = [{ name: 'byte-copy', outcome: 'maybe' }];
    }));
    expect(err.code).toBe('DISCLOSURE_RECORD_BAD_DOCUMENT');
    expect(err.message).toContain('maybe');
  });

  it('refuses a limits member wording its own claims instead of the format\'s sentence', () => {
    const err = refusalOf(edited((document) => { document['limits'] = 'This mark survives every transformation of any content.'; }));
    expect(err.code).toBe('DISCLOSURE_RECORD_BAD_DOCUMENT');
  });
});

describe('the reader refuses an unknown duty pointer shape', () => {
  it('refuses a label outside the registry, by its own code and with the label quoted', () => {
    for (const duty of ['ai-act-50-2', 'gdpr-13', '']) {
      const err = refusalOf(edited((document) => { document['duty'] = duty; }));
      expect(err.code, `duty ${JSON.stringify(duty)}`).toBe('DISCLOSURE_RECORD_UNKNOWN_DUTY');
    }
    expect(refusalOf(edited((document) => { document['duty'] = 'ai-act-50-2'; })).message).toContain('ai-act-50-2');
    expect(refusalOf(edited((document) => { document['duty'] = 5; })).code).toBe('DISCLOSURE_RECORD_BAD_DOCUMENT');
  });
});

describe('the reader refuses a scheme the marking registry does not carry', () => {
  it('answers with the marking registry\'s own code, naming the record position', () => {
    const err = refusalOf(edited((document) => { document['scheme'] = 'provenance-v2'; }));
    expect(err.code).toBe('UNSUPPORTED_SCHEME');
    expect(err.message).toContain('provenance-v2');
    expect(err.message).toContain('scheme');
    expect(refusalOf(edited((document) => { document['scheme'] = 5; })).code).toBe('DISCLOSURE_RECORD_BAD_DOCUMENT');
  });
});